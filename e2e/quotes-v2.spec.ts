  await page.getByLabel('整票体积 CBM',{exact:true}).fill('1');
  await page.getByLabel('总件数',{exact:true}).fill('5');
  await page.getByLabel('目的邮编',{exact:true}).fill('90001');
  await page.getByLabel('原表缺少材积系数时（选填）',{exact:true}).fill('6000');
