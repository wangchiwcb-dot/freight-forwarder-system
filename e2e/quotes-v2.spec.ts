test('creates and saves rule versions without losing unvisited tabs, tier IDs or nested conditions', async ({ page }) => {
  test.skip(process.env.E2E_V2_WRITE !== '1','只在本地开发库执行草稿写入测试');
  await page.goto('./#/');
  await page.getByRole('tab',{name:'原表价格查询',exact:true}).click();
  await page.getByRole('searchbox',{name:'搜索原表报价'}).fill('盐田定时达海派');
  await page.getByRole('searchbox',{name:'搜索原表报价'}).press('Enter');
  await page.getByRole('button',{name:'建立规则草稿'}).first().click();
  await page.getByRole('button',{name:'进入规则整理'}).click();
  const editor=page.getByRole('dialog',{name:'渠道价格与规则维护'});
  await expect(editor.getByLabel('渠道与目的地名称')).toBeVisible();
  await editor.getByLabel('渠道与目的地名称').fill('本地浏览器测试草稿，请勿发布');
  const firstSaved=page.waitForResponse(response=>response.url().endsWith('/api/v2/review/offers')&&response.request().method()==='POST');
  await editor.getByRole('button',{name:'保存新草稿版本'}).click();
  const savedResponse=await firstSaved;
  expect(savedResponse.status()).toBe(200);
  const first=(await savedResponse.json()).offer;
  expect(first.tiers).toHaveLength(3); expect(first.billing.volumeStepCbm).toBe('0.1');
  expect(first.tiers.every((tier:{id:string})=>tier.id)).toBe(true);
  await editor.getByRole('tab',{name:'价格档位',exact:true}).click();
  await editor.getByLabel('成本单价',{exact:true}).first().fill('15.5');
  await editor.getByRole('tab',{name:'附加费与拒收',exact:true}).click();
  await editor.getByRole('button',{name:'添加附加费或拒收规则'}).click();
  await editor.getByLabel('规则名称',{exact:true}).fill('本地验证附加费');
  await editor.getByLabel('费率 / 金额（拒收或待核可留空）',{exact:true}).fill('100');
  await editor.getByText('无条件适用',{exact:true}).click();
  await page.getByTitle('任一条件满足',{exact:true}).click();
  const secondSaved=page.waitForResponse(response=>response.url().endsWith('/api/v2/review/offers')&&response.request().method()==='POST');
  await editor.getByRole('button',{name:'保存新草稿版本'}).click();
  const secondResponse=await secondSaved;
  expect(secondResponse.status()).toBe(200);
  const second=(await secondResponse.json()).offer;
  expect(second.id).not.toBe(first.id); expect(second.channelId).toBe(first.channelId);
  expect(second.tiers[0].id).toBe(first.tiers[0].id); expect(second.tiers[0].unitPrice).toBe('15.5');
  expect(second.rules[0].id).toBeTruthy(); expect(second.rules[0].condition.op).toBe('any');
  expect(second.rules[0].condition.conditions[0]).toEqual({field:'destination.addressType',op:'eq',value:'residential'});
  await expect(editor.getByRole('button',{name:'发布当前版本'})).toBeDisabled();
});

