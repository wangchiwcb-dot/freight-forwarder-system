import { expect,test } from '@playwright/test';
test.skip(process.env.E2E_WEEKLY_FIXTURES!=='1','需要独立本地周更验收库');
test('previews and activates a weekly file, keeps other agents and retrieves both periods',async({page,request})=>{
  await page.goto('./#/');
  await page.getByRole('tab',{name:'原表价格查询',exact:true}).click();
  await page.getByRole('button',{name:'每周报价更新',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'每周报价更新',exact:true});
  await dialog.getByLabel('本期新报价表').click();
  await page.getByTitle('[验收] 10月28日新表.xlsx（1 条）',{exact:true}).click();
  await dialog.getByLabel('对应的上一期报价表').click();
  await page.getByTitle('[验收] 10月21日旧表.xlsx',{exact:true}).click();
  await dialog.getByLabel('本期名称').fill('周更验收 10月28日版');
  await dialog.getByLabel('本期生效日期').fill('2026-10-28');
  await dialog.getByRole('button',{name:'预览本期变化'}).click();
  await expect(dialog).toContainText('匹配 1');await expect(dialog).toContainText('沿用旧价 1');
  await expect(dialog).toContainText('0kg起: 10');await expect(dialog).toContainText('0kg起: 12');
  const activation=page.waitForResponse(r=>r.url().endsWith('/quote-updates/activate'));
  await dialog.getByRole('button',{name:'确认本期生效'}).click();expect((await activation).status()).toBe(200);
  await expect(dialog).toContainText('已确认“周更验收 10月28日版”');
  await page.screenshot({path:'.local/v2/weekly-updates-desktop.png',animations:'disabled'});
  await page.setViewportSize({width:390,height:844});
  await expect.poll(async()=>(await dialog.boundingBox())!.x).toBeGreaterThanOrEqual(0);
  await expect.poll(async()=>(await dialog.boundingBox())!.width).toBeLessThanOrEqual(390);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1)).toBe(true);
  await page.screenshot({path:'.local/v2/weekly-updates-mobile.png',animations:'disabled'});
  await page.setViewportSize({width:1440,height:1000});
  await dialog.locator('.ant-drawer-close').click();
  await page.getByLabel('查看报价日期').fill('2026-10-28');
  await page.getByRole('searchbox',{name:'搜索原表报价'}).fill('周更验收渠道 A');
  await page.getByRole('searchbox',{name:'搜索原表报价'}).press('Enter');
  const rows=page.getByRole('tabpanel',{name:'原表价格查询',exact:true}).locator('.ant-table-tbody');
  await expect(rows).toContainText('12 CNY/kg');await expect(rows).not.toContainText('10 CNY/kg');
  await page.getByLabel('查看报价日期').fill('2026-10-27');
  await expect(rows).toContainText('10 CNY/kg');await expect(rows).not.toContainText('12 CNY/kg');
  await page.getByRole('checkbox',{name:'包含历史和待生效报价'}).check();
  await expect(rows).toContainText('10 CNY/kg');await expect(rows).toContainText('12 CNY/kg');
  const retained=await request.get('/api/v2/price-drafts?asOf=2026-10-29&q=周更验收');
  const ids=(await retained.json()).items.map((r:any)=>r.id).sort();
  expect(ids).toEqual(['weekly-new','weekly-other','weekly-retained']);
});

test('renamed channels can be linked without editing the original workbook',async({page,request})=>{
  await page.goto('./#/');await page.getByRole('tab',{name:'原表价格查询',exact:true}).click();
  await page.getByRole('button',{name:'每周报价更新',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'每周报价更新',exact:true});
  await dialog.getByLabel('本期新报价表').click();await page.getByTitle('[验收] 11月4日改名表.xlsx（1 条）',{exact:true}).click();
  await dialog.getByLabel('对应的上一期报价表').click();await page.getByTitle('[验收] 10月28日新表.xlsx · 周更验收 10月28日版',{exact:true}).click();
  await dialog.getByLabel('本期名称').fill('周更验收 11月4日版');await dialog.getByLabel('本期生效日期').fill('2026-11-04');
  await dialog.getByRole('button',{name:'预览本期变化'}).click();await expect(dialog).toContainText('匹配 0');
  await dialog.getByRole('button',{name:'关联旧渠道',exact:true}).click();
  const match=page.getByRole('dialog',{name:'关联上一期渠道',exact:true});
  await match.getByRole('searchbox',{name:'搜索上一期渠道'}).fill('周更验收渠道 A');await match.getByRole('searchbox',{name:'搜索上一期渠道'}).press('Enter');
  await expect(match.locator('.ant-table-row')).toHaveCount(1);await match.getByRole('button',{name:'关联此渠道'}).click();
  await dialog.getByRole('button',{name:'预览本期变化'}).click();await expect(dialog).toContainText('匹配 1');
  await expect(dialog).toContainText('渠道名称或适用范围');await dialog.getByRole('button',{name:'确认本期生效'}).click();
  await expect(dialog).toContainText('已确认“周更验收 11月4日版”');
  const current=await request.get('/api/v2/price-drafts?asOf=2026-11-04&q=周更验收渠道 A');
  expect((await current.json()).items.map((r:any)=>r.id)).toEqual(['weekly-renamed']);
});

